export interface Transliterator {
  language: string;
  candidates(word: string): string[];
}
export const hindiTransliterator: Transliterator = {
  language: "hi",
  candidates(word) {
    if (!/^[a-z]+$/i.test(word)) return [word];
    // ITRANS treats capitals as different letters (T = ट, S = ष), but phone
    // keyboards capitalise the first word of a sentence. Phonetic input is
    // case-insensitive; familiar ksh/chh spellings map to ITRANS keys.
    const lower = word.toLowerCase();
    const phonetic = lower.replace(/ksh/g, "kSh").replace(/chh/g, "Ch");
    const fallback = Sanscript.t(phonetic, "itrans", "devanagari", {
      syncope: true,
    });
    return [...new Set([...(common[lower] ?? []), fallback, word])];
  },
};
